'## 基本思想\n不用比较，而是用**散列函数**把关键字直接映射到地址：**H(key) = key mod m**（除留余数法）。\n\n## 冲突与处理\n不同关键字映射到同一地址称为**冲突**（同义词）。两大处理方法：\n\n### 拉链法（链地址法）\n把所有同义词挂在同一个桶的**单链表**上。\n- 优点：不会抢占别人的位置；删除方便；装填因子可 > 1；\n- 缺点：指针额外开销，缓存局部性差。\n\n### 开放地址法（线性探测）\n冲突时向后逐个找空位：`Hi = (H(key) + di) mod m`，di = 1,2,3...\n- 优点：无需指针，缓存友好；\n- 缺点：容易**聚集**（连续占用区越来越长）；删除必须做**墓碑标记**而非直接清空。\n\n## 性能分析\n- 装填因子 **α = n / m**（表中记录数 / 表长）；\n- α 越大冲突越频繁，查找效率越低；\n- 工程上常保持 α ≤ 0.75，超过就**扩容 rehash**。\n- 平均查找长度 ASL：拉链法成功查找约 1 + α/2；线性探测约 ½(1 + 1/(1-α))。\n\n## 散列函数设计原则\n1. 计算简单、分布均匀；\n2. 尽量减少冲突；\n3. 常用方法：除留余数法、数字分析法、平方取中法、折叠法。\n\n## 考点提示\n1. 给定关键字序列和表长，手算各关键字的散列地址与最终存储图（高频大题）。\n2. 会算 ASL（成功 / 失败两种情况）。\n3. m 通常取**不超过表长的最大素数**，可减少周期性冲突。',
