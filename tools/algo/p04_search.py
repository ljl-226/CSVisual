def _gen_grid(r, n=None, m=None, obs_rate=0.25):
    n = n or r.randint(2, 8)
    m = m or r.randint(2, 8)
    rows = []
    for _ in range(n):
        rows.append(''.join('#' if r.random() < obs_rate else '.' for _ in range(m)))
    rows[0] = '.' + rows[0][1:]
    rows[-1] = rows[-1][:-1] + '.'
    return '%d %d\n%s' % (n, m, '\n'.join(rows))


