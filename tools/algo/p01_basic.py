def _gen_triangle(r):
    """生成一组必定能构成三角形的三边"""
    a = r.randint(2, 50)
    b = r.randint(2, 50)
    lo = abs(a - b) + 1
    hi = a + b - 1
    c = r.randint(lo, hi)
    return '%d %d %d' % (a, b, c)


